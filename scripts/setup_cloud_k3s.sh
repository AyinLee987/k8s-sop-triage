#!/usr/bin/env bash
# Rebuild the experiment environment in a Claude cloud session (Firecracker VM, cgroup v1, root, egress via
# an agent proxy). kind does not work there (nested runc fails), so this runs k3s directly on the VM.
#
# Usage: bash scripts/setup_cloud_k3s.sh /path/to/tiktok-k8s-lab
# Needs network access to: Docker Hub, GitHub release downloads, pypi.org.
# Idempotent enough to re-run after the VM restarts. See docs/ISSUES.md E-012 for why each workaround exists.
set -euo pipefail

LAB=${1:?usage: setup_cloud_k3s.sh /path/to/tiktok-k8s-lab}
REPO=$(cd "$(dirname "$0")/.." && pwd)
K3S_VERSION=${K3S_VERSION:-v1.33.5+k3s1}
NS=tiktok-k8s-lab
export KUBECONFIG=/etc/rancher/k3s/k3s.yaml
NOPROXY=(env -u HTTP_PROXY -u HTTPS_PROXY -u http_proxy -u https_proxy -u ALL_PROXY -u all_proxy)

log() { printf '\n== %s\n' "$*"; }

log "docker daemon"
if ! docker info >/dev/null 2>&1; then
  (dockerd >/tmp/dockerd.log 2>&1 &)
  for _ in $(seq 1 30); do docker info >/dev/null 2>&1 && break; sleep 1; done
fi

log "k3s binary + airgap system images (avoids Docker Hub rate limits for system pods)"
if ! command -v k3s >/dev/null; then
  v=${K3S_VERSION/+/%2B}
  curl -sSL -o /tmp/k3s "https://github.com/k3s-io/k3s/releases/download/$v/k3s"
  install -m 755 /tmp/k3s /usr/local/bin/k3s
fi
mkdir -p /var/lib/rancher/k3s/agent/images
if [ ! -s /var/lib/rancher/k3s/agent/images/k3s-airgap-images-amd64.tar.zst ]; then
  v=${K3S_VERSION/+/%2B}
  curl -sSL -o /var/lib/rancher/k3s/agent/images/k3s-airgap-images-amd64.tar.zst \
    "https://github.com/k3s-io/k3s/releases/download/$v/k3s-airgap-images-amd64.tar.zst"
fi
command -v kubectl >/dev/null || ln -sf /usr/local/bin/k3s /usr/local/bin/kubectl

start_k3s() {
  # Without the proxy variables: otherwise the API server reaches the local kubelet through the egress proxy.
  ("${NOPROXY[@]}" k3s server --disable traefik --disable servicelb --disable metrics-server \
      --write-kubeconfig-mode 600 --node-name tiktok-k8s-lab >/tmp/k3s.log 2>&1 &)
  for _ in $(seq 1 60); do kubectl get nodes 2>/dev/null | grep -q " Ready" && return 0; sleep 2; done
  echo "k3s did not become Ready; see /tmp/k3s.log" >&2; return 1
}

log "k3s server"
if ! kubectl get nodes >/dev/null 2>&1; then start_k3s; fi
# Two fixes that need k3s to have run once (it generates the containerd config and unpacks its binaries):
#  - k3s ships runc 1.3.x, which cannot start containers on this kernel; the system runc (1.5.x) can.
#  - the VM refuses to lower oom_score_adj, which fails every pod sandbox unless containerd caps it.
DATA=$(readlink -f /var/lib/rancher/k3s/data/current)
CDIR=/var/lib/rancher/k3s/agent/etc/containerd
if ! cmp -s /usr/bin/runc "$DATA/bin/runc" || [ ! -f "$CDIR/config.toml.tmpl" ]; then
  log "patch runc + containerd config, restart k3s"
  pkill -f "k3s server" || true; sleep 5
  cp /usr/bin/runc "$DATA/bin/runc"
  python3 - "$CDIR/config.toml" "$CDIR/config.toml.tmpl" <<'PY'
import sys
s = open(sys.argv[1]).read()
s = s.replace("# File generated by k3s. DO NOT EDIT. Use config.toml.tmpl instead.\n", "")
head = "[plugins.'io.containerd.cri.v1.runtime']\n"
assert head in s, "containerd config layout changed; check the k3s version"
s = s.replace(head, head + "  restrict_oom_score_adj = true\n", 1)
open(sys.argv[2], "w").write(s)
PY
  start_k3s
fi

log "storage class 'standard' (the manifests were written for kind)"
kubectl apply -f - <<'EOF'
apiVersion: storage.k8s.io/v1
kind: StorageClass
metadata:
  name: standard
provisioner: rancher.io/local-path
reclaimPolicy: Delete
volumeBindingMode: WaitForFirstConsumer
EOF

log "app image (dependencies from a host-side wheelhouse: the build container does not trust the egress proxy CA)"
B=$(mktemp -d)
cp -r "$LAB/app" "$LAB/scripts" "$LAB/requirements.txt" "$B/"
chmod -R a+rX "$B"   # sources copied from Windows can arrive without read permission for the non-root app user
pip download -q --only-binary=:all: --platform manylinux2014_x86_64 --platform manylinux_2_17_x86_64 \
  --python-version 3.12 --implementation cp -r "$B/requirements.txt" -d "$B/wheelhouse"
cat > "$B/Dockerfile" <<'EOF'
FROM python:3.12.15-slim-bookworm@sha256:34386ef0cb081344d7ec1c103ba398e6e9f64e9ab3a1509accc92a4e24a07258
ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1
WORKDIR /app
COPY requirements.txt .
COPY wheelhouse /tmp/wheelhouse
RUN pip install --no-cache-dir --no-index --find-links /tmp/wheelhouse -r requirements.txt && rm -rf /tmp/wheelhouse
COPY app ./app
COPY scripts/client.py ./scripts/client.py
RUN useradd --uid 10001 --create-home lab
ARG APP_VERSION=v1
ENV APP_VERSION=$APP_VERSION
USER 10001
EXPOSE 8000
CMD ["python", "-m", "uvicorn", "app.api:app", "--host", "0.0.0.0", "--port", "8000", "--timeout-graceful-shutdown", "10", "--no-access-log"]
EOF
docker build -q -t tiktok-k8s-lab:v1 "$B" >/dev/null
docker pull -q redis:7.4.2-alpine >/dev/null
docker save tiktok-k8s-lab:v1 redis:7.4.2-alpine | k3s ctr images import - >/dev/null
rm -rf "$B"

log "Redis password (generated here, never printed)"
mkdir -p "$LAB/.local" && chmod 700 "$LAB/.local"
if [ ! -s "$LAB/.local/redis-password.txt" ]; then
  python3 -c "import secrets,sys;open(sys.argv[1],'w').write(secrets.token_urlsafe(48))" "$LAB/.local/redis-password.txt"
fi
python3 -c "import sys;p=open(sys.argv[1]).read();open(sys.argv[2],'w').write(f'requirepass {p}\n')" \
  "$LAB/.local/redis-password.txt" "$LAB/.local/redis-auth.conf"
chmod 600 "$LAB/.local/"*

log "deploy tiktok-k8s-lab"
kubectl apply -f "$LAB/k8s/namespace.yaml" >/dev/null
if ! kubectl -n "$NS" get secret redis-auth >/dev/null 2>&1; then
  kubectl -n "$NS" create secret generic redis-auth \
    --from-file=password="$LAB/.local/redis-password.txt" \
    --from-file=redis-auth.conf="$LAB/.local/redis-auth.conf" >/dev/null
fi
kubectl apply -k "$LAB/k8s" >/dev/null
kubectl -n "$NS" rollout restart deploy/api deploy/worker >/dev/null
for t in statefulset/redis deploy/api deploy/worker; do kubectl -n "$NS" rollout status "$t" --timeout=180s; done

log "experiment config + read-only diagnoser credentials"
mkdir -p "$REPO/.local"
cp /etc/rancher/k3s/k3s.yaml "$REPO/.local/admin.kubeconfig" && chmod 600 "$REPO/.local/admin.kubeconfig"
if [ ! -f "$REPO/.env" ]; then
  sed -e "s#^LAB_K8S_DIR=.*#LAB_K8S_DIR=$LAB/k8s#" -e "s#^ADMIN_KUBECONFIG=.*#ADMIN_KUBECONFIG=.local/admin.kubeconfig#" \
      -e "s#^ADMIN_CONTEXT=.*#ADMIN_CONTEXT=default#" "$REPO/.env.example" > "$REPO/.env"
fi
cd "$REPO"
"${NOPROXY[@]}" python3 scripts/make_diag_kubeconfig.py
"${NOPROXY[@]}" python3 -m triage.runner check-env
log "done"
